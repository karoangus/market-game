export const CHAR_IDS = Object.keys(CHARS);
export function char(id) {
  return CHARS[id] || { name: id, emoji: '👤', role: '', desc: '', quotes: [] };
}
/** کاراکترهایی که در یک مکان حاضرند */
export function charsAt(locId) {
  return Object.entries(CHARS)
    .filter(([, c]) => c.where === locId)
    .map(([id, c]) => ({ id, ...c }));
}
/** کاراکترهای همراه (ورودی: فهرست شناسه‌ها) */
export function companions(list = []) {
  return list.map((id) => ({ id, ...char(id) }));
}
