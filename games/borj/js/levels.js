/** همهٔ سطرها را هم‌عرض می‌کند؛ تهی‌جاهای پایین نقشه را زمین می‌گیرد */
function pad(rows) {
  const w = Math.max(...rows.map((r) => r.length));
  return rows.map((r, i) => {
    const ground = i >= rows.length - 2;
    return r + (ground ? '#' : '.').repeat(w - r.length);
  });
}
