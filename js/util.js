// =============================================================
//  util.js — کمکی‌های عمومی (فرمت عدد فارسی و پول)
// =============================================================

/** فرمت عدد با ارقام فارسی */
export const fa = (n) =>
  Number(n).toLocaleString('fa-IR', { maximumFractionDigits: 1 });

/** فرمت پول: «۱۲ $» */
export const money = (n) => `${fa(n)} $`;

/** فرمت پول با علامت مثبت/منفی: «+۵ $» / «−۳ $» */
export const signedMoney = (n) =>
  `${n < 0 ? '−' : '+'}${fa(Math.abs(n))} $`;
